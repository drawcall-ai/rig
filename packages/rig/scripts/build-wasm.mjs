import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const source = fileURLToPath(new URL('../src/skin/wasm/', import.meta.url))
const fingerprint = createHash('sha256').update(readFileSync(join(source, 'blur.c'))).update(readFileSync(new URL(import.meta.url))).digest('hex')
const header = `// Generated from blur.c by scripts/build-wasm.mjs. Source SHA256: ${fingerprint}`
if (process.argv.includes('--check')) {
  if (!readFileSync(join(source, 'bytes.ts'), 'utf8').startsWith(header + '\n')) {
    throw new Error('Rig WASM is stale. Run pnpm --filter @drawcall/rig build:wasm and commit the generated bytes.ts.')
  }
  process.exit(0)
}

const llvm = execFileSync('em-config', ['LLVM_ROOT'], { encoding: 'utf8' }).trim()
const cache = execFileSync('em-config', ['CACHE'], { encoding: 'utf8' }).trim()
const temporary = mkdtempSync(join(tmpdir(), 'rig-wasm-'))
try {
  const common = [
    '--target=wasm32-unknown-emscripten', `--sysroot=${cache}/sysroot`,
    '-O3', '-ffp-contract=off', '-fno-vectorize', '-fno-slp-vectorize', '-nostdlib',
    '-Wl,--no-entry', '-Wl,--import-memory', '-Wl,--initial-memory=131072',
    '-Wl,--max-memory=2147483648', '-Wl,--export=__stack_pointer', '-Wl,--export=blur',
    join(source, 'blur.c'),
  ]
  const definitions = []
  for (const name of ['single', 'shared']) {
    const output = join(temporary, `${name}.wasm`)
    const flags = name === 'shared' ? ['-matomics', '-mbulk-memory', '-Wl,--shared-memory'] : []
    execFileSync(join(llvm, 'clang'), [...common, ...flags, '-o', output], { stdio: 'inherit' })
    definitions.push(`export const ${name} = '${readFileSync(output).toString('base64')}'`)
  }
  writeFileSync(join(source, 'bytes.ts'), `${header}\n// Embedded to avoid bundler-specific WASM loaders.\n${definitions.join('\n')}\n`)
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
